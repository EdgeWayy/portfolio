  document.addEventListener('click', (e) => {
    const b = e.target.closest('[data-lang]');
    if (b) set(b.dataset.lang);
  });

  document.documentElement.lang = lang;
  apply();

  return { lang, locale: LOCALE, t, pick, apply, set, switcher };
